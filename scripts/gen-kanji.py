#!/usr/bin/env python3
"""Regenerate src/domain/kanji.ts, the committed JLPT N5-N1 kanji catalog.

Joins two sources at run time:
  - KANJIDIC2 (https://www.edrdg.org/kanjidic/kanjidic2.xml.gz), copyright
    EDRDG, CC BY-SA 4.0 (https://www.edrdg.org/edrdg/licence.html) --
    supplies each card's first 3 English meanings, its on'yomi (katakana)
    and its kun'yomi (hiragana, okurigana dot removed: まな.ぶ -> まなぶ).
  - Jonathan Waller's JLPT N5-N1 kanji lists (tanos.co.uk, CC BY), which
    limit the catalog to those levels and fix each level's order.
    tanos.co.uk itself is unreachable (NXDOMAIN since late 2026), so the
    generator reads the CC BY mirror of its parsed CSVs instead:
    https://github.com/Bluskyo/JLPT_Vocabulary -- whose 79-kanji N5 list
    was verified against independent reproductions of Waller's list.

The five lists are disjoint today (79+166+367+367+1232 = 2211 unique
kanji); if one ever drifts into another, the lower level keeps the kanji
and the higher occurrence is skipped. A listed kanji KANJIDIC2 cannot
supply (no entry, or no English meanings) is skipped with a warning
rather than blocking regeneration -- the catalog tests pin the per-level
counts, so any skip surfaces as a count change in review.

ShareAlike: the emitted catalog derives from KANJIDIC2, so it carries the
same CC BY-SA obligation -- hence the licence header the script writes.
Needs network and a python3; run via `mise run gen-kanji`.
"""

import gzip
import sys
import unicodedata
import urllib.request
import xml.etree.ElementTree as ET

KANJIDIC2_URL = "https://www.edrdg.org/kanjidic/kanjidic2.xml.gz"
LIST_URL = (
    "https://raw.githubusercontent.com/Bluskyo/JLPT_Vocabulary"
    "/main/data/kanji/parsedData/{level}_kanji.csv"
)
OUT_PATH = "src/domain/kanji.ts"
MAX_MEANINGS = 3

# Raw per-list counts, asserted so a changed list is source drift to check
# by hand, not a silently different catalog. Levels in ascending order.
LEVEL_COUNTS = {"n5": 79, "n4": 166, "n3": 367, "n2": 367, "n1": 1232}

HEADER = """\
// GENERATED by scripts/gen-kanji.py (`mise run gen-kanji`) -- never edit by
// hand; regenerate instead.
//
// Source data and licences -- the ShareAlike term of the first applies to
// this derived catalog:
// - This adapted catalog is distributed under GPL-3.0-only, a licence
//   compatible with CC BY-SA 4.0; upstream KANJIDIC2 copyright and licence
//   terms continue to apply to its data.
// - KANJIDIC2, (c) EDRDG, CC BY-SA 4.0
//   (https://www.edrdg.org/kanjidic/kanjidic2.xml.gz,
//   licence https://www.edrdg.org/edrdg/licence.html): meanings and
//   readings. First 3 English meanings kept; kun'yomi dot-free.
// - Jonathan Waller's JLPT N5-N1 kanji lists (tanos.co.uk), CC BY, read
//   from the CC BY mirror https://github.com/Bluskyo/JLPT_Vocabulary
//   because tanos.co.uk was unreachable when this file was generated.

import type { KanjiCard } from './cards';

// Each card goes through this identity function so the array literal is
// KanjiCard[] from its first element: `satisfies` (or plain contextual
// typing) on a 2,211-element literal makes tsc build a union too complex
// to represent (TS2590), while the parameter still checks every card.
function kanji(card: KanjiCard): KanjiCard {
  return card;
}

// Frozen like the kana catalog's CARDS: shared module state that no caller
// may corrupt (docs/agents/coding-standards.md rule 6). The cards
// themselves are frozen where they merge into CARDS.
export const KANJI_CARDS: readonly KanjiCard[] = Object.freeze([
"""


def download(url: str) -> bytes:
    with urllib.request.urlopen(url) as response:
        return response.read()


def load_level(level: str) -> list[str]:
    text = download(LIST_URL.format(level=level)).decode("utf-8")
    kanji = [line.strip() for line in text.splitlines() if line.strip()]
    headerless = [k for k in kanji if k != "Kanji"]
    expected = LEVEL_COUNTS[level]
    if len(headerless) != expected:
        sys.exit(f"expected {expected} {level.upper()} kanji, the list has {len(headerless)} -- source drift?")
    return headerless


def parse_kanjidic2() -> dict[str, dict[str, list[str]]]:
    root = ET.fromstring(gzip.decompress(download(KANJIDIC2_URL)))
    entries: dict[str, dict[str, list[str]]] = {}
    for character in root.findall("character"):
        literal = character.findtext("literal")
        meanings = [
            meaning.text or ""
            for meaning in character.findall("reading_meaning/rmgroup/meaning")
            if "m_lang" not in meaning.attrib
        ]
        onyomi = [
            r.text or "" for r in character.findall("reading_meaning/rmgroup/reading[@r_type='ja_on']")
        ]
        kunyomi = [
            (r.text or "").replace(".", "")
            for r in character.findall("reading_meaning/rmgroup/reading[@r_type='ja_kun']")
        ]
        entries[literal] = {
            "meanings": meanings[:MAX_MEANINGS],
            "onyomi": onyomi,
            "kunyomi": kunyomi,
        }
    return entries


def ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_array(values: list[str]) -> str:
    return "[" + ", ".join(ts_string(v) for v in values) + "]"


def card_line(grapheme: str, level: str, entry: dict[str, list[str]]) -> str:
    # NFC, matching how domain/cards.ts builds every catalog id.
    literal = unicodedata.normalize("NFC", grapheme)
    return (
        "  kanji({"
        + ", ".join(
            [
                f"cardId: {ts_string(literal + ':kanji')}",
                f"grapheme: {ts_string(literal)}",
                "script: 'kanji'",
                f"set: {ts_string(level)}",
                f"meanings: {ts_array(entry['meanings'])}",
                f"onyomi: {ts_array(entry['onyomi'])}",
                f"kunyomi: {ts_array(entry['kunyomi'])}",
            ]
        )
        + "}),\n"
    )


def main() -> None:
    kanjidic2 = parse_kanjidic2()
    seen: set[str] = set()
    emitted = 0
    with open(OUT_PATH, "w", encoding="utf-8") as out:
        out.write(HEADER)
        for level, _ in LEVEL_COUNTS.items():
            for grapheme in load_level(level):
                literal = unicodedata.normalize("NFC", grapheme)
                if literal in seen:
                    print(f"skipping {literal} at {level.upper()}: already in a lower level's Set")
                    continue
                # Claimed here, before the data checks, so the lower level
                # always wins even when its occurrence is the one skipped.
                seen.add(literal)
                entry = kanjidic2.get(literal)
                if entry is None:
                    print(f"skipping {literal} at {level.upper()}: no KANJIDIC2 entry")
                    continue
                if not entry["meanings"]:
                    print(f"skipping {literal} at {level.upper()}: no English meanings")
                    continue
                out.write(card_line(literal, level, entry))
                emitted += 1
        out.write("]);\n")
    print(f"wrote {OUT_PATH}: {emitted} kanji cards across N5-N1")


if __name__ == "__main__":
    main()
