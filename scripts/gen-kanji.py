#!/usr/bin/env python3
"""Regenerate src/domain/kanji.ts, the committed JLPT N5 kanji catalog.

Joins two sources at run time:
  - KANJIDIC2 (https://www.edrdg.org/kanjidic/kanjidic2.xml.gz), copyright
    EDRDG, CC BY-SA 4.0 (https://www.edrdg.org/edrdg/licence.html) --
    supplies each card's first 3 English meanings, its on'yomi (katakana)
    and its kun'yomi (hiragana, okurigana dot removed: まな.ぶ -> まなぶ).
  - Jonathan Waller's JLPT N5 kanji list (tanos.co.uk, CC BY), which limits
    the catalog to N5 and fixes its order. tanos.co.uk itself is
    unreachable (NXDOMAIN since late 2026), so the generator reads the CC BY
    mirror of its parsed CSVs instead:
    https://github.com/Bluskyo/JLPT_Vocabulary -- whose 79-kanji N5 list
    was verified against independent reproductions of Waller's list.

ShareAlike: the emitted catalog derives from KANJIDIC2, so it carries the
same CC BY-SA obligation -- hence the licence header the script writes.
Needs network and a python3; run via `mise run gen-kanji`.
"""

import gzip
import sys
import unicodedata
import urllib.request
import xml.etree.ElementTree as ET

KANJIDIC2_URL = "https://www.edrdg.org/kanjidic/kanjidic2.xml.gz"
N5_LIST_URL = (
    "https://raw.githubusercontent.com/Bluskyo/JLPT_Vocabulary"
    "/main/data/kanji/parsedData/n5_kanji.csv"
)
OUT_PATH = "src/domain/kanji.ts"
MAX_MEANINGS = 3

HEADER = """\
// GENERATED by scripts/gen-kanji.py (`mise run gen-kanji`) -- never edit by
// hand; regenerate instead.
//
// Source data and licences -- the ShareAlike term of the first applies to
// this derived catalog:
// - KANJIDIC2, (c) EDRDG, CC BY-SA 4.0
//   (https://www.edrdg.org/kanjidic/kanjidic2.xml.gz,
//   licence https://www.edrdg.org/edrdg/licence.html): meanings and
//   readings. First 3 English meanings kept; kun'yomi dot-free.
// - Jonathan Waller's JLPT N5 kanji list (tanos.co.uk), CC BY, read from
//   the CC BY mirror https://github.com/Bluskyo/JLPT_Vocabulary because
//   tanos.co.uk was unreachable when this file was generated.

import type { KanjiCard } from './cards';

// Frozen like the kana catalog's CARDS: shared module state that no caller
// may corrupt. The cards themselves are frozen where they merge into CARDS.
export const KANJI_CARDS: readonly KanjiCard[] = Object.freeze([
"""


def download(url: str) -> bytes:
    with urllib.request.urlopen(url) as response:
        return response.read()


def load_n5() -> list[str]:
    text = download(N5_LIST_URL).decode("utf-8")
    kanji = [line.strip() for line in text.splitlines() if line.strip()]
    headerless = [k for k in kanji if k != "Kanji"]
    if len(headerless) != 79:
        sys.exit(f"expected 79 N5 kanji, the list has {len(headerless)} -- source drift?")
    return headerless


def parse_kanjidic2() -> dict[str, dict[str, list[str]]]:
    root = ET.fromstring(gzip.decompress(download(KANJIDIC2_URL)))
    entries: dict[str, dict[str, list[str]]] = {}
    for character in root.findall("character"):
        literal = character.findtext("literal")
        meanings = [
            meaning.text or ""
            for meaning in character.findall("reading_meaning/rmgroup/meaning")
            if "m_lang" not in meaning.attrib
        ]
        onyomi = [
            r.text or "" for r in character.findall("reading_meaning/rmgroup/reading[@r_type='ja_on']")
        ]
        kunyomi = [
            (r.text or "").replace(".", "")
            for r in character.findall("reading_meaning/rmgroup/reading[@r_type='ja_kun']")
        ]
        entries[literal] = {
            "meanings": meanings[:MAX_MEANINGS],
            "onyomi": onyomi,
            "kunyomi": kunyomi,
        }
    return entries


def ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_array(values: list[str]) -> str:
    return "[" + ", ".join(ts_string(v) for v in values) + "]"


def card_line(grapheme: str, entry: dict[str, list[str]]) -> str:
    # NFC, matching how domain/cards.ts builds every catalog id.
    literal = unicodedata.normalize("NFC", grapheme)
    return (
        "  {"
        + ", ".join(
            [
                f"cardId: {ts_string(literal + ':kanji')}",
                f"grapheme: {ts_string(literal)}",
                "script: 'kanji'",
                "set: 'n5'",
                f"meanings: {ts_array(entry['meanings'])}",
                f"onyomi: {ts_array(entry['onyomi'])}",
                f"kunyomi: {ts_array(entry['kunyomi'])}",
            ]
        )
        + "},\n"
    )


def main() -> None:
    n5 = load_n5()
    kanjidic2 = parse_kanjidic2()
    with open(OUT_PATH, "w", encoding="utf-8") as out:
        out.write(HEADER)
        for grapheme in n5:
            entry = kanjidic2.get(unicodedata.normalize("NFC", grapheme))
            if entry is None:
                sys.exit(f"no KANJIDIC2 entry for {grapheme}")
            if not entry["meanings"]:
                sys.exit(f"no English meanings for {grapheme}")
            out.write(card_line(grapheme, entry))
        # Frozen like the kana catalog's CARDS: shared module state that no
        # caller may corrupt (docs/agents/coding-standards.md rule 6). The
        # cards themselves are frozen where they merge into CARDS.
        out.write("] satisfies KanjiCard[]);\n")
    print(f"wrote {OUT_PATH}: {len(n5)} N5 kanji cards")


if __name__ == "__main__":
    main()
